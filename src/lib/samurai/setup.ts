// Samurai's guided setup for one site: check the server, install (or upgrade)
// the spinuptui-nginx gate and register the site with it, make this machine's
// deploy key, mirror the site's live nginx config, and prove the whole path by
// pushing Samurai's (empty) rules file through the gate and checking the site
// from outside. Spec: docs/2026-11-11_samurai-spec.md, "Guided setup".
//
// planSetup only reads. applySetup does what the plan shows, in order, and
// stops at the first failure. The one root step goes through the server's sudo
// user (runSudoServerOp), with the bundle inside the script it sends.

import { existsSync, mkdirSync, readFileSync, writeFileSync, chmodSync, readdirSync, rmSync } from "node:fs"
import { hostname } from "node:os"
import { join } from "node:path"
import type { Server, Site } from "../../api/types.ts"
import { moduleStateDir } from "../../modules/contract.ts"
import { spawn } from "../spawn.ts"
import { lastErrorLine, runSshStdin, runSudoServerOp } from "../ssh.ts"
import { checkGate, GATE_FILE, GATE_SHA256, GATE_VERSION, gateScriptText, INSTALLER_FILE, installerText, SERVER_PATHS } from "./gate.ts"
import { gateCall, gateError, text, type GateTarget } from "./remote.ts"

export const SAMURAI_FILE = "server/samurai.conf"
export const SAMURAI_HEADER = `# Samurai (SpinupTUI): this site's nginx rules, one block per applied to-do.
# Regenerated by SpinupTUI from its to-do list on every change; don't edit it
# here or on the server, or the next change will overwrite the edit.
`
const MARKER = "__SAMURAI_SETUP_OK__"
const TLS_IGNORE = "*.pem\n*.key\n*.crt\n*.csr\n*.p12\n*.pfx\n"

export const samuraiDir = () => moduleStateDir("samurai")
export const keyPath = (domain: string) => join(samuraiDir(), "keys", domain)
export const mirrorDir = (domain: string) => join(samuraiDir(), "mirrors", domain)

// Whether this machine has done setup for a site: its deploy key and its
// mirror both exist. The server side is checked when it's used.
export function setUpHere(domain: string): boolean {
  return existsSync(`${keyPath(domain)}.pub`) && existsSync(join(mirrorDir(domain), ".git"))
}

export interface SetupContext {
  domain: string
  site: Site
  server: Server
  sudo: { user: string; password: string } | null // null: not connected
}

// What the server says, read as the sudo user without sudo.
export interface ServerState {
  siteDir: boolean
  realip: boolean
  gate: { version: string | null; hash: string | null } | null
  allowed: string[] | null // null: the site isn't registered
  keys: string[]
  oldGateSite: boolean // the proof of concept's gate serves this site
  samuraiFile: boolean
}

export interface SetupStep {
  id: "check" | "gate" | "register" | "key" | "mirror" | "prove"
  title: string
  detail: string
  done: boolean
}

export type SetupPlan =
  | {
      ok: true
      domain: string
      sshTarget: string
      gateTarget: GateTarget
      state: ServerState
      steps: SetupStep[]
      needsSudo: boolean
      writes: string[] // every path the root step writes, for the confirm screen
      allow: string[] // the allowlist the site will have
      keys: string[] // the deploy keys it will have
      localKey: { path: string; exists: boolean; pub: string | null }
      mirror: { path: string; exists: boolean }
      notes: string[]
    }
  | { ok: false; reason: SetupFailure; message: string; remedy?: string }

export type SetupFailure = "no_ip" | "no_sudo_user" | "ssh_failed" | "no_site_dir" | "old_gate" | "sudo_failed" | "key_failed" | "gate_failed" | "mirror_failed" | "prove_failed" | "site_down"

export function parseServerState(out: string): ServerState {
  const sections: Record<string, string[]> = {}
  let cur = ""
  for (const line of out.split("\n")) {
    const m = /^==([A-Z]+)$/.exec(line.trim())
    if (m) {
      cur = m[1]!
      sections[cur] = []
    } else if (cur && line.trim()) sections[cur]!.push(line.trim())
  }
  const one = (k: string) => sections[k]?.[0] ?? null
  const gateHash = one("GATEHASH")
  return {
    siteDir: one("SITEDIR") === "yes",
    realip: one("REALIP") === "yes",
    gate: gateHash ? { version: one("GATEVER"), hash: gateHash } : null,
    allowed: one("REGISTERED") === "yes" ? (sections.ALLOWED ?? []).filter((l) => !l.startsWith("#")) : null,
    keys: (sections.KEYS ?? []).filter((l) => l.startsWith("ssh-")),
    oldGateSite: one("OLDGATE") === "yes",
    samuraiFile: one("SAMURAI") === "yes",
  }
}

// Read-only, as the sudo user: none of it needs sudo, since the gate (755),
// its config dir and the site's allowlist and keys (644) are world-readable.
export function stateScript(domain: string): string {
  const site = `/etc/nginx/sites-available/${domain}`
  const conf = `${SERVER_PATHS.sites}/${domain}`
  return [
    "echo ==SITEDIR",
    `test -d ${site} && echo yes`,
    "echo ==REALIP",
    `/usr/sbin/nginx -V 2>&1 | grep -q with-http_realip_module && echo yes`,
    "echo ==GATEHASH",
    `sha256sum ${SERVER_PATHS.gate} 2>/dev/null | cut -d' ' -f1`,
    "echo ==GATEVER",
    `grep -m1 '^VERSION=' ${SERVER_PATHS.gate} 2>/dev/null | cut -d= -f2`,
    "echo ==REGISTERED",
    `test -f ${conf}.allowed && echo yes`,
    "echo ==ALLOWED",
    `cat ${conf}.allowed 2>/dev/null`,
    "echo ==KEYS",
    `cat ${conf}.pub 2>/dev/null`,
    "echo ==OLDGATE",
    `test -f /etc/spinupwp-nginx-deploy/sites/${domain}.allowed && echo yes`,
    "echo ==SAMURAI",
    `test -e ${site}/${SAMURAI_FILE} && echo yes`,
    "true",
  ].join("\n")
}

const keyBlob = (line: string) => line.trim().split(/\s+/)[1] ?? ""

export async function planSetup(ctx: SetupContext): Promise<SetupPlan> {
  const ip = ctx.server.ip_address
  if (!ip) return { ok: false, reason: "no_ip", message: `${ctx.server.name} has no IP address in SpinupWP.` }
  if (!ctx.sudo?.user) {
    return {
      ok: false,
      reason: "no_sudo_user",
      message: `SpinupTUI doesn't know ${ctx.server.name}'s sudo user yet.`,
      remedy: "Connect sudo on that server first: press S on it in the Servers tab, and tick \"remember\" so commands can use it too.",
    }
  }
  const port = ctx.server.ssh_port ?? null
  const sshTarget = `${ctx.sudo.user}@${ip}`
  const r = await runSshStdin(sshTarget, port, "bash -s", stateScript(ctx.domain), 30_000)
  if (r.code !== 0) return { ok: false, reason: "ssh_failed", message: `Couldn't read ${ctx.server.name} as ${ctx.sudo.user}: ${lastErrorLine(r.stderr || r.stdout, `ssh exit ${r.code}`)}` }
  const state = parseServerState(r.stdout)
  if (!state.siteDir) return { ok: false, reason: "no_site_dir", message: `${ctx.server.name} has no nginx config for ${ctx.domain} at /etc/nginx/sites-available/${ctx.domain}.` }
  if (state.oldGateSite) {
    return {
      ok: false,
      reason: "old_gate",
      message: `${ctx.domain} is on the earlier nginx-deploy tool, which this setup doesn't touch.`,
      remedy: "Move it with the one-off migration script first; setup then adopts it.",
    }
  }

  const kp = keyPath(ctx.domain)
  const pub = existsSync(`${kp}.pub`) ? readFileSync(`${kp}.pub`, "utf8").trim() : null
  const gateOk = state.gate ? checkGate(state.gate).ok : false
  const allow = [...new Set([...(state.allowed ?? []), SAMURAI_FILE])]
  const registeredOk = !!state.allowed?.includes(SAMURAI_FILE) && !!pub && state.keys.some((k) => keyBlob(k) === keyBlob(pub))
  // Keys other machines registered stay; this machine's is added.
  const keys = [...state.keys]
  const others = keys.filter((k) => !pub || keyBlob(k) !== keyBlob(pub)).length
  const mirror = mirrorDir(ctx.domain)
  const mirrorExists = existsSync(join(mirror, ".git"))

  const steps: SetupStep[] = [
    {
      id: "check",
      title: "Check the server",
      detail: `${ctx.domain}'s nginx config is at /etc/nginx/sites-available/${ctx.domain}. ${state.realip ? "nginx has the real-IP module, which the Cloudflare rule needs." : "nginx has no real-IP module, so the Cloudflare rule won't be offered here."}`,
      done: true,
    },
    {
      id: "gate",
      title: state.gate ? (gateOk ? "The gate is installed" : "Upgrade the gate") : "Install the gate",
      detail: gateOk
        ? `spinuptui-nginx ${GATE_VERSION} is already installed, unchanged.`
        : `As root: the gate at ${SERVER_PATHS.gate}, a sudoers rule letting the ${SERVER_PATHS.user} user run that one command, and that user.${state.gate ? ` Replaces version ${state.gate.version ?? "unknown"}.` : ""}`,
      done: gateOk,
    },
    {
      id: "key",
      title: pub ? "This machine's deploy key exists" : "Make this machine's deploy key",
      detail: pub ? `${kp}` : `A new ed25519 key at ${kp}, used only for ${ctx.domain}'s nginx rules.`,
      done: !!pub,
    },
    {
      id: "register",
      title: registeredOk ? `${ctx.domain} is registered` : `Register ${ctx.domain} with the gate`,
      detail: `As root: allow ${allow.join(", ")} and nothing else, for ${others ? `this machine's deploy key plus ${others} already registered` : "this machine's deploy key"}. A key can act on ${ctx.domain} only.`,
      done: registeredOk,
    },
    {
      id: "mirror",
      title: mirrorExists ? "Refresh the local copy of its nginx config" : "Copy its nginx config here",
      detail: `A git repository of the live config at ${mirror}. Certificates and keys never leave the server.`,
      done: false,
    },
    {
      id: "prove",
      title: "Prove it end to end",
      detail: `Push ${state.samuraiFile ? "the current" : "an empty"} ${SAMURAI_FILE} through the gate (nginx -t, then reload), then check ${ctx.domain} still answers as it did before.`,
      done: false,
    },
  ]
  const needsSudo = !gateOk || !registeredOk
  const writes = needsSudo
    ? [SERVER_PATHS.gate, SERVER_PATHS.sudoers, `${SERVER_PATHS.sites}/${ctx.domain}.allowed`, `${SERVER_PATHS.sites}/${ctx.domain}.pub`, `${SERVER_PATHS.home}/.ssh/authorized_keys`, `user ${SERVER_PATHS.user}`, `${SERVER_PATHS.backups}/${ctx.domain}/ (by the gate, from the first push)`]
    : []
  const notes: string[] = []
  if (needsSudo && !ctx.sudo.password) notes.push(`The root step needs ${ctx.sudo.user}'s sudo password, which isn't saved in the Keychain.`)

  return {
    ok: true,
    domain: ctx.domain,
    sshTarget,
    gateTarget: { ip, port, keyPath: kp },
    state,
    steps,
    needsSudo,
    writes,
    allow,
    keys,
    localKey: { path: kp, exists: !!pub, pub },
    mirror: { path: mirror, exists: mirrorExists },
    notes,
  }
}

// The script sent to `sudo -S bash -s`: the bundle as heredocs, then install.sh.
export function registerScript(domain: string, allow: string[], keys: string[]): string {
  const b64 = (s: string) => Buffer.from(s).toString("base64").replace(/(.{76})/g, "$1\n")
  return `set -euo pipefail
d=$(mktemp -d)
trap 'rm -rf "$d"' EXIT
base64 -d > "$d/${GATE_FILE}" <<'SAMURAI_B64'
${b64(gateScriptText())}
SAMURAI_B64
base64 -d > "$d/${INSTALLER_FILE}" <<'SAMURAI_B64'
${b64(installerText())}
SAMURAI_B64
cat > "$d/${domain}.allowed" <<'SAMURAI_EOF'
${allow.join("\n")}
SAMURAI_EOF
cat > "$d/${domain}.pub" <<'SAMURAI_EOF'
${keys.join("\n")}
SAMURAI_EOF
[ "$(sha256sum "$d/${GATE_FILE}" | cut -d' ' -f1)" = "${GATE_SHA256}" ] || { echo "ERROR: the gate arrived damaged; nothing was installed" >&2; exit 1; }
bash "$d/${INSTALLER_FILE}" ${domain} </dev/null
echo ${MARKER}
`
}

async function run(cmd: string[], opts: { cwd?: string; stdin?: Uint8Array; env?: Record<string, string> } = {}): Promise<{ code: number; out: Uint8Array; err: string }> {
  const p = spawn(cmd, { cwd: opts.cwd, stdin: opts.stdin ? "pipe" : "ignore", stdout: "pipe", stderr: "pipe", env: opts.env ? { ...process.env, ...opts.env } : undefined })
  const out = new Response(p.stdout as ReadableStream<Uint8Array>).arrayBuffer()
  const err = new Response(p.stderr as ReadableStream<Uint8Array>).text()
  if (opts.stdin && p.stdin) {
    const sink = p.stdin as { write: (b: Uint8Array) => void; end: () => void }
    sink.write(opts.stdin)
    sink.end()
  }
  const code = await p.exited
  return { code, out: new Uint8Array(await out), err: await err }
}

// Commits as the user when git knows them, else as SpinupTUI.
const GIT_ID = { GIT_AUTHOR_NAME: "SpinupTUI", GIT_AUTHOR_EMAIL: "samurai@spinuptui.invalid", GIT_COMMITTER_NAME: "SpinupTUI", GIT_COMMITTER_EMAIL: "samurai@spinuptui.invalid" }
async function git(dir: string, ...args: string[]) {
  const named = (await run(["git", "config", "user.email"], { cwd: dir })).code === 0
  return run(["git", "-C", dir, ...args], named ? {} : { env: GIT_ID })
}

export async function ensureKey(domain: string): Promise<{ ok: true; pub: string } | { ok: false; message: string }> {
  const kp = keyPath(domain)
  if (existsSync(`${kp}.pub`)) return { ok: true, pub: readFileSync(`${kp}.pub`, "utf8").trim() }
  mkdirSync(join(samuraiDir(), "keys"), { recursive: true })
  chmodSync(join(samuraiDir(), "keys"), 0o700)
  const machine = hostname().split(".")[0]
  const r = await run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", `spinuptui-nginx ${domain} ${machine}`, "-f", kp])
  if (r.code !== 0) return { ok: false, message: `ssh-keygen failed: ${r.err.trim()}` }
  return { ok: true, pub: readFileSync(`${kp}.pub`, "utf8").trim() }
}

// Makes the mirror match the server's export, and commits any difference as
// its own "Sync from server" commit (or the first, "Initial mirror").
export async function syncMirror(domain: string, target: GateTarget): Promise<{ ok: true; changed: boolean } | { ok: false; message: string }> {
  const dir = mirrorDir(domain)
  const fresh = !existsSync(join(dir, ".git"))
  if (fresh) {
    mkdirSync(dir, { recursive: true })
    const i = await git(dir, "init", "-q", "-b", "main")
    if (i.code !== 0) return { ok: false, message: `git init failed: ${i.err.trim()}` }
    writeFileSync(join(dir, ".gitignore"), TLS_IGNORE)
  }
  const exp = await gateCall(target, "export")
  if (exp.code !== 0 || exp.stdout.length === 0) return { ok: false, message: `The gate's export failed: ${gateError(exp, `ssh exit ${exp.code}`)}` }
  // Replace everything but git's own files, so deletions on the server show.
  for (const name of readdirSync(dir)) if (name !== ".git" && name !== ".gitignore") rmSync(join(dir, name), { recursive: true, force: true })
  const x = await run(["tar", "-x", "-C", dir], { stdin: exp.stdout })
  if (x.code !== 0) return { ok: false, message: `Unpacking the export failed: ${x.err.trim()}` }
  await git(dir, "add", "-A")
  const st = await git(dir, "status", "--porcelain")
  if (!text(st.out)) return { ok: true, changed: false }
  const c = await git(dir, "commit", "-q", "-m", fresh ? "Initial mirror of server config" : "Sync from server")
  if (c.code !== 0) return { ok: false, message: `git commit failed: ${c.err.trim() || text(c.out)}` }
  return { ok: true, changed: true }
}

// Sends the committed version of the given files through the gate.
export async function deployCommitted(domain: string, target: GateTarget, files: string[]): Promise<{ ok: true; log: string } | { ok: false; message: string }> {
  const a = await run(["git", "-C", mirrorDir(domain), "archive", "--format=tar", "HEAD", "--", ...files])
  if (a.code !== 0) return { ok: false, message: `git archive failed: ${a.err.trim()}` }
  const d = await gateCall(target, "deploy", a.out, 120_000)
  if (d.code !== 0) return { ok: false, message: gateError(d, `deploy failed (ssh exit ${d.code})`) }
  return { ok: true, log: d.stderr.trim() }
}

// What the site answers from outside, without following redirects.
export async function homeStatus(domain: string): Promise<number | null> {
  try {
    const r = await fetch(`https://${domain}/`, { redirect: "manual", signal: AbortSignal.timeout(20_000), headers: { "user-agent": "SpinupTUI-Samurai/1 (setup check)" } })
    return r.status
  } catch {
    return null
  }
}

export interface ApplyResult {
  ok: true
  mirrorChanged: boolean
  deployLog: string
  before: number | null
  after: number | null
}

export async function applySetup(
  plan: Extract<SetupPlan, { ok: true }>,
  ctx: SetupContext,
  onStage: (line: string) => void = () => {},
): Promise<ApplyResult | { ok: false; reason: SetupFailure; message: string; remedy?: string }> {
  onStage("Making this machine's deploy key")
  const key = await ensureKey(ctx.domain)
  if (!key.ok) return { ok: false, reason: "key_failed", message: key.message }

  if (plan.needsSudo) {
    if (!ctx.sudo?.user) return { ok: false, reason: "no_sudo_user", message: "No sudo user for this server." }
    const keys = [...plan.keys.filter((k) => keyBlob(k) !== keyBlob(key.pub)), key.pub]
    onStage(`Installing the gate and registering ${ctx.domain} (as root, through ${ctx.sudo.user})`)
    const r = await runSudoServerOp(ctx.server, { sudoUser: ctx.sudo.user, sudoPassword: ctx.sudo.password }, () => registerScript(ctx.domain, plan.allow, keys), MARKER)
    if (!r.ok) return { ok: false, reason: "sudo_failed", message: `The root step failed: ${r.error}` }
  }

  onStage("Checking the gate answers to this machine's key")
  const [v, h] = [await gateCall(plan.gateTarget, "version"), await gateCall(plan.gateTarget, "hash")]
  if (v.code !== 0) return { ok: false, reason: "gate_failed", message: `The gate didn't answer: ${gateError(v, `ssh exit ${v.code}`)}` }
  const g = checkGate({ version: text(v.stdout), hash: text(h.stdout) })
  if (!g.ok) return { ok: false, reason: "gate_failed", message: g.message }

  onStage(plan.mirror.exists ? "Refreshing the local copy of the config" : "Copying the site's nginx config here")
  const m = await syncMirror(ctx.domain, plan.gateTarget)
  if (!m.ok) return { ok: false, reason: "mirror_failed", message: m.message }

  const dir = mirrorDir(ctx.domain)
  if (!existsSync(join(dir, SAMURAI_FILE))) {
    writeFileSync(join(dir, SAMURAI_FILE), SAMURAI_HEADER)
    await git(dir, "add", SAMURAI_FILE)
    const c = await git(dir, "commit", "-q", "-m", "Samurai: start an empty rules file")
    if (c.code !== 0) return { ok: false, reason: "mirror_failed", message: `git commit failed: ${c.err.trim()}` }
  }

  onStage(`Checking ${ctx.domain} from outside, before`)
  const before = await homeStatus(ctx.domain)
  onStage(`Pushing ${SAMURAI_FILE} through the gate (nginx -t, then reload)`)
  const d = await deployCommitted(ctx.domain, plan.gateTarget, [SAMURAI_FILE])
  if (!d.ok) return { ok: false, reason: "prove_failed", message: `The push failed, and the gate restored the previous config: ${d.message}` }
  onStage(`Checking ${ctx.domain} from outside, after`)
  const after = await homeStatus(ctx.domain)
  if (after === null || (after >= 500 && (before === null || before < 500))) {
    return {
      ok: false,
      reason: "site_down",
      message: `${ctx.domain} answered ${after ?? "nothing"} after the push (${before ?? "nothing"} before). The rules file only holds comments, so this is unlikely to be Samurai's doing, but check the site now.`,
    }
  }
  return { ok: true, mirrorChanged: m.changed, deployLog: d.log, before, after }
}
